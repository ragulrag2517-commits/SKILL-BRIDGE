import os
import re
import sqlite3

from sqlalchemy import create_engine
from sqlalchemy.orm import sessionmaker
from sqlalchemy.pool import StaticPool

from config import BASE_DIR, DATABASE_PATH
from database.models import Base


SCHEMA_FILE = os.path.join(BASE_DIR, 'database', 'schema.sql')
DATABASE_URL = os.environ.get('SKILLBRIDGE_DATABASE_URL', '').strip()

if DATABASE_URL:
    sqlalchemy_url = DATABASE_URL
    if sqlalchemy_url.startswith('postgres://'):
        sqlalchemy_url = sqlalchemy_url.replace('postgres://', 'postgresql+psycopg://', 1)
    elif sqlalchemy_url.startswith('postgresql://'):
        sqlalchemy_url = sqlalchemy_url.replace('postgresql://', 'postgresql+psycopg://', 1)
    engine = create_engine(sqlalchemy_url, pool_pre_ping=True)
else:
    engine = create_engine(
        f'sqlite:///{DATABASE_PATH}',
        connect_args={'check_same_thread': False},
        poolclass=StaticPool,
    )
SessionLocal = sessionmaker(bind=engine, autoflush=False, autocommit=False)


class _PostgresRow(dict):
    def __getitem__(self, key):
        if isinstance(key, int):
            return tuple(self.values())[key]
        return super().__getitem__(key)


class _PostgresResult:
    def __init__(self, cursor, inserted_id=None):
        self._cursor = cursor
        self.lastrowid = inserted_id
        self.rowcount = cursor.rowcount

    def fetchone(self):
        row = self._cursor.fetchone()
        return _PostgresRow(row) if row is not None else None

    def fetchall(self):
        return [_PostgresRow(row) for row in self._cursor.fetchall()]


class _PostgresConnection:
    def __init__(self, connection):
        self._connection = connection

    def execute(self, query, parameters=()):
        query = query.strip()
        if query.upper().startswith('PRAGMA '):
            return _PostgresResult(self._connection.cursor())
        if query.upper() == 'BEGIN IMMEDIATE':
            query = 'BEGIN'

        query = re.sub(
            r'([A-Za-z_][A-Za-z0-9_.]*deadline)\s*>=\s*date\([\'"]now[\'"]\)',
            r'CAST(\1 AS DATE) >= CURRENT_DATE',
            query,
            flags=re.IGNORECASE,
        )
        query = re.sub(r"\bdate\('now'\)", 'CURRENT_DATE', query, flags=re.IGNORECASE)
        query = re.sub(r'\bdate\(([^()]+)\)', r'CAST(\1 AS DATE)', query, flags=re.IGNORECASE)
        ignore_insert = bool(re.match(r'INSERT\s+OR\s+IGNORE\s+INTO\b', query, re.IGNORECASE))
        if ignore_insert:
            query = re.sub(r'INSERT\s+OR\s+IGNORE\s+INTO\b', 'INSERT INTO', query, count=1, flags=re.IGNORECASE)
            if not re.search(r'\bON\s+CONFLICT\b', query, re.IGNORECASE):
                query = query.rstrip().rstrip(';') + ' ON CONFLICT DO NOTHING'

        insert_id = bool(re.match(r'INSERT\s+INTO\b', query, re.IGNORECASE))
        if insert_id and not re.search(r'\bRETURNING\b', query, re.IGNORECASE):
            query = query.rstrip().rstrip(';') + ' RETURNING id'
        query = query.replace('?', '%s')

        cursor = self._connection.cursor()
        cursor.execute(query, tuple(parameters or ()))
        inserted_id = None
        if insert_id and cursor.description:
            returned = cursor.fetchone()
            if returned is not None:
                inserted_id = returned['id']
        return _PostgresResult(cursor, inserted_id)

    def executescript(self, script):
        statements = [
            statement.strip()
            for statement in script.split(';')
            if statement.strip() and not statement.strip().upper().startswith('PRAGMA ')
        ]
        result = None
        for statement in statements:
            statement = re.sub(
                r'INTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT',
                'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY',
                statement,
                flags=re.IGNORECASE,
            )
            statement = re.sub(r'\bBLOB\b', 'BYTEA', statement, flags=re.IGNORECASE)
            result = self.execute(statement)
        return result

    def commit(self):
        self._connection.commit()

    def rollback(self):
        self._connection.rollback()

    def close(self):
        self._connection.close()


def get_db_connection():
    if DATABASE_URL:
        import psycopg
        from psycopg.rows import dict_row

        return _PostgresConnection(
            psycopg.connect(DATABASE_URL, row_factory=dict_row)
        )
    conn = sqlite3.connect(DATABASE_PATH)
    conn.row_factory = sqlite3.Row
    conn.execute('PRAGMA foreign_keys = ON')
    return conn


def get_db_session():
    return SessionLocal()


def init_db():
    Base.metadata.create_all(bind=engine)
    conn = get_db_connection()
    try:
        with open(SCHEMA_FILE, 'r', encoding='utf-8') as schema_file:
            schema_sql = schema_file.read()
        if schema_sql.strip():
            conn.executescript(schema_sql)

        migrations = {
            'industry_profiles': {
                'location': 'TEXT',
                'contact_email': 'TEXT',
                'contact_phone': 'TEXT',
                'logo_filename': 'TEXT',
                'verification_requested_at': 'TEXT',
            },
            'student_profiles': {
                'resume_filename': 'TEXT',
                'resume_data': 'BLOB',
            },
            'opportunities': {
                'qualification_requirements': 'TEXT',
                'minimum_cgpa': 'REAL',
                'openings': 'INTEGER NOT NULL DEFAULT 1',
                'status': "TEXT NOT NULL DEFAULT 'published'",
                'updated_at': 'TEXT',
                'is_demo': 'INTEGER NOT NULL DEFAULT 0',
            },
            'learning_programs': {
                'is_demo': 'INTEGER NOT NULL DEFAULT 0',
            },
            'opportunity_skills': {
                'skill_category': "TEXT NOT NULL DEFAULT 'technical'",
                'is_required': 'INTEGER NOT NULL DEFAULT 1',
            },
        }
        if DATABASE_URL:
            for table_name, columns in migrations.items():
                for column_name, column_definition in columns.items():
                    if column_definition.startswith('BLOB'):
                        column_definition = 'BYTEA' + column_definition[4:]
                    conn.execute(
                        f'ALTER TABLE {table_name} ADD COLUMN IF NOT EXISTS '
                        f'{column_name} {column_definition}'
                    )
        else:
            for table_name, columns in migrations.items():
                existing_columns = {
                    row['name'] for row in conn.execute(f'PRAGMA table_info({table_name})').fetchall()
                }
                for column_name, column_definition in columns.items():
                    if column_name not in existing_columns:
                        conn.execute(
                            f'ALTER TABLE {table_name} ADD COLUMN {column_name} {column_definition}'
                        )
        conn.execute(
            """
            UPDATE opportunities SET is_demo = 1
            WHERE company_id = (
                SELECT id FROM users WHERE email = 'industry@skillbridge.demo'
            ) AND title IN (
                'Healthcare Data Analyst Intern', 'Biomedical Software Developer',
                'Clinical Research Data Associate', 'Digital Health Product Engineer'
            )
            """
        )
        conn.execute(
            """
            UPDATE learning_programs SET is_demo = 1
            WHERE provider = 'SkillBridge Academy' AND title IN (
                'Python fundamentals', 'SQL and database management', 'React development',
                'Machine learning fundamentals', 'Data visualization',
                'Healthcare data analytics', 'Research methodology'
            )
            """
        )
        conn.commit()
    finally:
        conn.close()


